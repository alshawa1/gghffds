class TargetCustomersModule:
    CLASS_COL    = "العملاء المستهدفة"
    CATEGORY_COL = "تصنيف الاستهداف"
    PRIORITY_COL = "أولوية التحصيل"
    REASON_COL   = "سبب التصنيف"

    def run(
        self,
        portfolio: pl.DataFrame,
        promise: pl.DataFrame = None,
        maharah: pl.DataFrame = None,
        **kwargs,
    ) -> Dict:
        _log.info("▶ بدء تحديد العملاء المستهدفة (تطبيق الفلترة المزدوجة المعززة مع الكشف المرن للأعمدة)")

        # كشف عمود الهوية
        id_col = _detect_col(portfolio, _ID_COLS)
        if id_col:
            portfolio = portfolio.with_columns(
                (pl.lit(1.0) / pl.col(id_col).count().over(id_col).cast(pl.Float64)).alias("عدد العملاء")
            )
        else:
            portfolio = portfolio.with_columns(pl.lit(1.0).alias("عدد العملاء"))

        df = portfolio.clone()
        df = self._classify(df)

        positive_df = df.filter(pl.col(self.CLASS_COL) == POSITIVE)

        # كشف المشرف والمحصل للبيفوت
        sup_col = _detect_col(df, _SUPERVISOR_COLS)
        col_col = _detect_col(df, _COLLECTOR_COLS)

        piv_sup = self._build_pivot(df, sup_col) if sup_col else pl.DataFrame()
        piv_col = self._build_pivot(df, col_col) if col_col else pl.DataFrame()

        total = len(df)
        pos_count = df.filter(pl.col(self.CLASS_COL) == POSITIVE).height
        neg_count = df.filter(pl.col(self.CLASS_COL) == NEGATIVE).height

        category_counts = {}
        if pos_count > 0:
            cat_df = positive_df.group_by(self.CATEGORY_COL).len()
            for r in cat_df.iter_rows(named=True):
                key = r[self.CATEGORY_COL]
                if key is None:
                    key = "مستهدف (أخرى/حالة نظام)"
                category_counts[key] = int(r["len"])

        stats = {
            "إجمالي العملاء":    total,
            "مستهدف":            pos_count,
            "غير مستهدف":        neg_count,
            "نسبة المستهدفين %": round(pos_count / total * 100, 1) if total else 0.0,
        }
        stats.update(category_counts)

        return {
            "data":             df,
            "positive_data":    positive_df,
            "pivot_supervisor": piv_sup,
            "pivot_collector":  piv_col,
            "stats":            stats,
        }

    def _normalize_text(self, text_col: str) -> pl.Expr:
        return (
            pl.col(text_col)
            .fill_null("")
            .cast(pl.String)
            .str.strip_chars()
            .str.to_lowercase()
            .str.replace_all("أ", "ا")
            .str.replace_all("إ", "ا")
            .str.replace_all("آ", "ا")
            .str.replace_all("ة", "ه")
            .str.replace_all("ى", "ي")
        )

    def _classify(self, df: pl.DataFrame) -> pl.DataFrame:
        # الكشف الذكي المرن عن الأعمدة الأساسية
        note_col = _detect_col(df, _NOTE_COLS)
        main_col = _detect_col(df, _MAIN_STATUS_COLS)
        sub_col  = _detect_col(df, _SUB_STATUS_COLS)

        _log.info("الأعمدة المكتشفة للعملاء المستهدفة: المتابعة=%s, الحالة الرئيسية=%s, الحالة الفرعية=%s",
                  note_col, main_col, sub_col)

        # إذا لم يتوفر كولوم المتابعة ولا كولوم الحالة
        if not note_col and not main_col and not sub_col:
            _log.warning("لم يتم العثور على عمود المتابعة أو الحالة!")
            return df.with_columns([
                pl.lit(NEGATIVE).alias(self.CLASS_COL),
                pl.lit("❌ غير مستهدف").alias(self.CATEGORY_COL),
                pl.lit("لا يوجد عمود متابعة أو حالة").alias(self.REASON_COL),
                pl.lit(2).cast(pl.Int32).alias(self.PRIORITY_COL),
            ])

        note_expr = self._normalize_text(note_col) if note_col else pl.lit("")
        main_expr = self._normalize_text(main_col) if main_col else pl.lit("")
        sub_expr  = self._normalize_text(sub_col)  if sub_col  else pl.lit("")

        def _to_regex(kws):
            return "|".join(
                re.escape(
                    kw.replace("أ", "ا")
                    .replace("إ", "ا")
                    .replace("آ", "ا")
                    .replace("ة", "ه")
                    .replace("ى", "ي")
                )
                for kw in kws
            )

        # ── 1. فحص الرفض الصريح المانع أولاً وقبل كل شيء ────────────────────────
        disqualify_re = _to_regex(DISQUALIFY_REFUSALS)
        has_disqualify = note_expr.str.contains(disqualify_re, literal=False)
        extracted_disqualify = note_expr.str.extract(f"({disqualify_re})", 1)

        disqualify_reason_expr = (
            pl.when(has_disqualify)
            .then(pl.concat_str([pl.lit("مستبعد: "), extracted_disqualify.fill_null("")]))
            .otherwise(pl.lit("استبعاد / عدم تجاوب"))
        )

        # قناع النفي (Negation Masking) لمنع مطابقة "ما بيسدد" مع "بيسدد"
        neg_re = _to_regex(NEGATED_PAYMENT_PHRASES)
        masked_note_expr = note_expr.str.replace_all(neg_re, " REJECTED_PAYMENT ")

        # ── 2. فحص الحالات الأساسية المقبولة في النظام (Primary Status) ──────
        primary_main_re = _to_regex(PRIMARY_MAIN_STATUSES)
        primary_sub_re  = _to_regex(PRIMARY_SUB_STATUSES)

        has_primary_status = (
            main_expr.str.contains(primary_main_re, literal=False) |
            sub_expr.str.contains(primary_sub_re, literal=False)
        )

        # إذا لم يتوفر عمود الحالة الرئيسية أصلاً في المحفظة، نعتمد كلياً على كولوم المتابعة
        if not main_col and not sub_col:
            has_primary_status = pl.lit(True)

        # ── 3. فحص السداد الكامل (مستبعد فوراً لأنه تم السداد وخلاص) ───────────
        fully_paid_re = _to_regex(FULLY_PAID_KEYWORDS)
        # ملاحظة: السداد الكامل يُفحص في الملاحظة أو الحالة الرئيسية فقط (وليس الحالة الفرعية)
        has_fully_paid = (
            note_expr.str.contains(fully_paid_re, literal=False) |
            main_expr.str.contains(fully_paid_re, literal=False)
        )

        # ── 4. فحص الفئات الإيجابية الموسعة في كولوم المتابعة ──────────────────
        category_expr_list = []
        has_any_positive_note = pl.lit(False)

        for cat_name, kw_list in TARGET_CATEGORIES.items():
            cat_re = _to_regex(kw_list)
            cat_match = masked_note_expr.str.contains(cat_re, literal=False)
            has_any_positive_note = has_any_positive_note | cat_match
            category_expr_list.append(
                pl.when(cat_match).then(pl.lit(cat_name)).otherwise(pl.lit(None))
            )

        pos_category_expr = pl.coalesce(category_expr_list)

        # ── 5. هل يوجد مؤشر إيجابي صريح في الحالة النظامية نفسها؟ ─────────────
        system_explicit_promise_re = _to_regex([
            "واعد بالسداد", "سداد جزئي", "الورثة واعدين", "ورثة واعدين", "طلب مهلة", "طلب مهلة للسداد"
        ])
        has_explicit_system_promise = (
            main_expr.str.contains(system_explicit_promise_re, literal=False) |
            sub_expr.str.contains(system_explicit_promise_re, literal=False)
        )

        # ── 6. قاعدة الاستهداف المعززة (ضمان عدم تفويت أي حالة إيجابية) ────────
        # المعايير:
        # 1- لم يتم سداد كامل المديونية (~has_fully_paid)
        # 2- ليس رفضاً صريحاً مانعاً (~has_disqualify)
        # 3- وجود مؤشر إيجابي:
        #    - إما كلمة إيجابية صريحة في المتابعة (has_any_positive_note)
        #    - أو حالة نظامية إيجابية صريحة (has_explicit_system_promise)
        is_targeted = (
            (~has_fully_paid) &
            (~has_disqualify) &
            (
                has_any_positive_note |
                (has_explicit_system_promise & has_primary_status)
            )
        )

        class_expr = pl.when(is_targeted).then(pl.lit(POSITIVE)).otherwise(pl.lit(NEGATIVE))

        category_result_expr = (
            pl.when(is_targeted)
            .then(
                pl.coalesce([
                    pos_category_expr,
                    pl.when(has_explicit_system_promise).then(pl.lit("🤝 وعد سداد معتمد بالنظام")).otherwise(pl.lit("مستهدف إيجابي"))
                ])
            )
            .otherwise(pl.lit("❌ غير مستهدف"))
        )

        reason_result_expr = (
            pl.when(has_fully_paid)
            .then(pl.lit("✅ تم سداد كامل المديونية"))
            .otherwise(
                pl.when(has_disqualify)
                .then(disqualify_reason_expr)
                .otherwise(
                    pl.when(is_targeted & has_any_positive_note)
                    .then(pl.lit("مؤشر إيجابي صريح في كولوم المتابعة بالسداد / الدخل / الموعد"))
                    .otherwise(
                        pl.when(is_targeted & has_explicit_system_promise)
                        .then(pl.lit("حالة النظام معتمدة: واعد بالسداد / سداد جزئي"))
                        .otherwise(pl.lit("لا تتوفر عبارات سداد إيجابية"))
                    )
                )
            )
        )

        df = df.with_columns([
            class_expr.alias(self.CLASS_COL),
            category_result_expr.alias(self.CATEGORY_COL),
            reason_result_expr.alias(self.REASON_COL),
            pl.when(is_targeted).then(pl.lit(1)).otherwise(pl.lit(2)).cast(pl.Int32).alias(self.PRIORITY_COL)
        ])

        return df

    def _build_pivot(self, df: pl.DataFrame, group_col: Optional[str]) -> pl.DataFrame:
        if not group_col or group_col not in df.columns:
            return pl.DataFrame()

        try:
            pivot = (
                df.group_by([group_col, self.CLASS_COL])
                .len()
                .pivot(on=self.CLASS_COL, index=group_col, values="len")
                .fill_null(0)
            )
            for col in [POSITIVE, NEGATIVE]:
                if col not in pivot.columns:
                    pivot = pivot.with_columns(pl.lit(0).alias(col))
            pivot = pivot.with_columns(
                (pl.col(POSITIVE) + pl.col(NEGATIVE)).alias("الإجمالي")
            )
            return pivot
        except Exception as e:
            _log.warning("فشل إنشاء جدول المحور لـ %s: %s", group_col, e)
            return pl.DataFrame()
